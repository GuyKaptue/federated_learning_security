R = Path(__file__).resolve().parents[1]
D = R / "docs" / "datasets"; D.mkdir(parents=True, exist_ok=True)

CLAR = """## Clarifications that apply to every dataset in this project
* **SYN-IDS-v1 is completely synthetic despite its name.** It is generated by scikit-learn `make_classification`; it is not real intrusion-detection data and not patient data.
* **No real hospital data is used and no patient-identifiable data exists anywhere in the project.** The public healthcare tables are de-identified research datasets published by their owners.
* **All federated-learning clients are simulated locally** in one process (virtual clients). The four natural "sites" of the heart-disease data are four 1980s research cohorts, not live hospital federations.
* **Raw source datasets are not redistributed** with the repository. They are downloaded on first use into `data/raw/<dataset>/` and refused if their SHA-256 differs from the pinned value.
* **Some datasets are fetched from public third-party mirrors.** The licence of the original dataset is documented where it could be read on the original source page; the licence of the mirror itself was *not* verified.
* **CIC-IDS-2017 was not available and is not used** in the final implementation. Results on SYN-IDS-v1 must never be compared numerically with CIC-IDS-2017 results.
* **No credentialed clinical repository (e.g. PhysioNet MIMIC-IV, eICU) was available, so none is used** in the paper or in the code. No electronic-health-record data are present anywhere in this project.
"""

syn_cfg = SynIDSConfig(); Xs, ys = generate_raw(syn_cfg)
rows = [("SYN-IDS-v1 (synthetic)", syn_cfg.n_samples, syn_cfg.n_features, float(ys.mean()), "generated (scikit-learn)", "n/a (generated, no restrictions)",
         "simulated IID / Dirichlet / shard clients", "FL benchmarks, crypto overhead, secure aggregation, attacks, defences, scalability, HPO")]
POS = {}
for a, label in (("wdbc", "Breast Cancer Wisconsin (Diagnostic)"), ("pima", "Pima Indians Diabetes"), ("heart", "Heart Disease, Cleveland (processed)")):
    X, y, _ = _raw(a); s = [x for x in SPECS.values() if x.alias == a][0]; POS[a] = (X, y)
    lic = {"wdbc": "CC BY 4.0", "pima": "not verified (no licence statement found; mirror unknown)", "heart": "CC BY 4.0 (original UCI dataset); mirror unverified"}[a]
    src = {"wdbc": "UCI, via scikit-learn (bundled)", "pima": "public GitHub mirror (original: NIDDK)", "heart": "UCI, via public GitHub mirror"}[a]
    rows.append((label, f"{len(y)} (303 raw, 1 duplicate removed)" if a == "heart" else len(y), X.shape[1], float(y.mean()), src, lic,
                 "simulated IID / Dirichlet clients", "validation on real, de-identified tables"))
site = {s: _site_raw(s) for s in SITE_NAMES}; ntot = sum(len(v[1]) for v in site.values()); ptot = sum(v[1].sum() for v in site.values())
rows.append(("UCI Heart Disease, four sites", ntot, 10, float(ptot / ntot), "UCI / public GitHub mirror (pinned commit)", "CC BY 4.0 (original); mirror unverified",
             "4 natural site clients (Cleveland, Hungary, Switzerland, VA Long Beach)", "natural heterogeneity; within-site and leave-one-site-out validation"))

HEAD = "| Dataset | Samples | Features | Positive rate | Source | License | Federated setup | Purpose in experiments |\n|---|---|---|---|---|---|---|---|\n"
TABLE = HEAD + "\n".join(f"| {a} | {b} | {c} | {d:.3f} | {e} | {f} | {g} | {h} |" for a, b, c, d, e, f, g, h in rows)
CAT = "| Dataset | Samples | Features | Target | Source | License | Usage |\n|---|---|---|---|---|---|---|\n" + "\n".join(
    [f"| SYN-IDS-v1 | {syn_cfg.n_samples} | {syn_cfg.n_features} | binary class (60/40 target) | generated by `make_classification` | n/a | FL benchmarks, crypto, attacks, defences, scalability, HPO |"] +
    [f"| {s.title} | {s.n_samples} | {s.n_features} | {s.target} | [{s.source_page.split(' ')[0]}]({s.source_page.split(' ')[0]}) | {s.license} ({s.license_status}) | {s.usage} |" for s in SPECS.values()])

(D / "_summary_table.md").write_text(TABLE + "\n")

def sha_block(key):
    s = SPECS[key]
    return "\n".join(f"| `{f.filename}` | `{f.sha256}` |" for f in s.files)

